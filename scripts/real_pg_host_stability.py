def probe_url(url, token=None, body=None, timeout=8):
    headers = {'Content-Type': 'application/json'}
    if token:
        headers['Authorization'] = 'Bearer ' + token
    req = urllib.request.Request(url, data=body, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            return response.status, json.loads(response.read())
    except urllib.error.HTTPError as error:
        return error.code, json.loads(error.read())


def pg_states(conn):
    with conn.cursor() as cursor:
        cursor.execute('SELECT state, count(*) FROM pg_stat_activity '
                       'WHERE datname=%s AND application_name=%s GROUP BY state',
                       (DB_NAME, 'PyLocalInventory-LAN'))
        result = {str(state or 'unknown'): count for state, count in cursor.fetchall()}
    conn.rollback()
    return result


def run_workload(port, password, seconds):
    profile = type('IsolatedProfile', (), {'database_name': DB_NAME,
                'get_value': lambda self, key: ''})()
    manager = type('IsolatedManager', (), {'selected_profile': profile})()
    database = Database(manager)
    database.registered_classes = {'Products': ProductClass}
    config = {'host': '127.0.0.1', 'port': port, 'user': DB_USER, 'password': '',
              'database': DB_NAME}
    server = None
    monitor_conn = None
    clients = []
    log = logging.getLogger('core.network.server')
    try:
        with patch('core.network.server.load_server_config', return_value=config):
            server = DatabaseServer(database, port=0)
            server.start()
        base = f'http://127.0.0.1:{server.port}'
        status, _ = probe_url(base + '/health')
        if status != 401:
            raise RuntimeError('Unauthenticated health contract changed')
        monitor_conn = connect(port, DB_NAME, application='PyLocalInventory-Phase15-Monitor')
        clients = [RemoteDatabase(None, '127.0.0.1', server.port,
                                  'isolated-admin', password) for _ in range(6)]
        for client in clients:
            client.connect()
        token = clients[0]._token
        status, response = probe_url(base + '/health', token=token)
        if status != 200 or not all(response.values()):
            raise RuntimeError('Authenticated service health failed')
        for client in clients:
            if len(client.get_items('Products', limit=10)) != 10:
                raise RuntimeError('Real PostgreSQL RPC read failed')
        for client in clients:
            client.close()
        server.stop()
        with patch('core.network.server.load_server_config', return_value=config):
            server = DatabaseServer(database, port=server.port)
            server.start()
        base = f'http://127.0.0.1:{server.port}'
        if probe_url(base + '/health', token=token)[0] != 401:
            raise RuntimeError('Host restart did not invalidate the old session')
        clients = [RemoteDatabase(None, '127.0.0.1', server.port,
                                  'isolated-admin', password) for _ in range(6)]
        for client in clients:
            client.connect()
        result = run_real_scenarios(server, clients, monitor_conn, port, password, seconds)
        return result
    finally:
        for client in clients:
            client.close()
        if server is not None:
            server.stop()
        if monitor_conn is not None and server is not None:
            print(json.dumps({'host_after_stop': {
                'thread_alive': server.is_running,
                'pool_checked_out': server._checked_out,
                'postgres_lan_connections': pg_states(monitor_conn),
                'threads': threading.active_count(),
                'tcp_sockets_including_monitor': tcp_sockets_for_process(),
                'working_set_mb': resident_memory_mb(),
            }}), flush=True)
        if monitor_conn is not None:
            monitor_conn.close()


def run_real_scenarios(server, clients, monitor_conn, port, password, seconds):
    """Functional failure probes followed by bounded multi-client traffic."""
    base = f'http://127.0.0.1:{server.port}'
    token = clients[0]._token

    # Exhaust exactly this newly created cluster's 10-connection pool, then
    # return everything before starting workload. Never touch other sessions.
    leases = []
    try:
        leases = [server._borrow_database() for _ in range(10)]
        if server._checked_out != 10:
            raise AssertionError('Pool checkout instrumentation disagrees')
        if probe_url(base + '/health', token=token)[0] != 503:
            raise AssertionError('Pool exhaustion was not exposed as health 503')
        if probe_url(base + '/rpc', token=token,
                     body=b'{"method":"get_items","args":["Products"]}')[0] != 503:
            raise AssertionError('Pool exhaustion RPC response was not 503')
    finally:
        for lease in leases:
            server._return_database(lease)
    if server._checked_out or probe_url(base + '/health', token=token)[0] != 200:
        raise AssertionError('Pool did not recover after checkouts were returned')

    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as concurrent_clients:
        sleepers = [concurrent_clients.submit(client._call, 'cursor.execute',
                     ['SELECT pg_sleep(0.35)', []], None, 3) for client in clients]
        for future in sleepers:
            if 'rows' not in future.result(timeout=5):
                raise AssertionError('Long SQL operation did not complete')

    locker = connect(port, DB_NAME, application='PyLocalInventory-Phase15-RowLock')
    try:
        with locker.cursor() as cursor:
            cursor.execute('SELECT id FROM products WHERE id=1 FOR UPDATE')
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as blocked:
            future = blocked.submit(clients[0]._call, 'cursor.execute',
                ['UPDATE products SET name = name WHERE id = 1', []], None, 5)
            time.sleep(.25)
            if future.done():
                raise AssertionError('Row-lock contention was not reproduced')
            if probe_url(base + '/health', token=token)[0] != 200:
                raise AssertionError('Host stopped serving health during row-lock wait')
            locker.rollback()
            if future.result(timeout=5)['rowcount'] != 1:
                raise AssertionError('Blocked operation did not recover')
    finally:
        locker.rollback()
        locker.close()

    # Terminate only a backend borrowed from THIS isolated pool, not a
    # PostgreSQL service or anyone else's connection.
    borrowed = server._borrow_database()
    with monitor_conn.cursor() as cursor:
        cursor.execute('SELECT pg_terminate_backend(%s)', (borrowed.conn.get_backend_pid(),))
        terminated = cursor.fetchone()[0]
    monitor_conn.rollback()
    server._return_database(borrowed)
    if not terminated or server._checked_out:
        raise AssertionError('Isolated backend termination left a checked-out connection')
    interruption_codes = []
    for _ in range(6):
        code, _ = probe_url(base + '/health', token=token)
        interruption_codes.append(code)
        if code == 200:
            break
        time.sleep(.1)
    print(json.dumps({'isolated_backend_interruption': {
        'health_status_sequence': interruption_codes,
        'pool_checked_out': server._checked_out,
    }}), flush=True)
    if interruption_codes[-1] != 200:
        raise AssertionError('Isolated backend termination did not eventually recover')

    detached = socket.create_connection(('127.0.0.1', server.port), timeout=3)
    body = b'{"method":"cursor.execute","args":["SELECT pg_sleep(0.4)",[]]}'
    detached.sendall((f'POST /rpc HTTP/1.1\r\nHost: 127.0.0.1\r\n'
                      f'Authorization: Bearer {token}\r\nContent-Length: {len(body)}\r\n\r\n').encode() + body)
    detached.close()
    time.sleep(.6)
    if server._checked_out:
        raise AssertionError('Disconnected Client stranded a PostgreSQL lease')

    if seconds <= 0:
        print(json.dumps({'real_pg_functional': 'passed', 'test_database': DB_NAME,
                          'pool_max': 10, 'database_states': pg_states(monitor_conn),
                          'host_healthy': server.is_running}), flush=True)
        return

    started = time.monotonic()
    cpu_start = time.process_time()
    samples = []
    rpc_latencies = []
    failed = {}
    health_latencies = []
    bursts = 0
    attempts = 0
    recovered = 0
    auth_count = len(clients)
    health_token = token
    stop_monitor = threading.Event()

    def monitor():
        while not stop_monitor.is_set():
            start = time.perf_counter()
            try:
                status, payload = probe_url(base + '/health', token=health_token, timeout=4)
                if status != 200 or not all(payload.values()):
                    failed['health_bad_status'] = failed.get('health_bad_status', 0) + 1
            except Exception as exc:
                key = 'health_' + type(exc).__name__
                failed[key] = failed.get(key, 0) + 1
            health_latencies.append((time.perf_counter() - start) * 1000)
            try:
                states = pg_states(monitor_conn)
            except Exception as exc:
                states = {'monitor_error': type(exc).__name__}
                failed['pg_monitor_error'] = failed.get('pg_monitor_error', 0) + 1
            samples.append({'t': round(time.monotonic() - started, 1),
                            'ram_mb': resident_memory_mb(),
                            'threads': threading.active_count(),
                            'tcp_sockets': tcp_sockets_for_process(),
                            'pool_in_use': server._checked_out,
                            'http_active': server._httpd.active_requests,
                            'pg_states': states,
                            'sessions': len(server.sessions._sessions)})
            stop_monitor.wait(2)

    def one_client(client, iteration):
        times = []
        errors = {}
        for offset in range(8):
            start = time.perf_counter()
            try:
                kind = (iteration * 8 + offset) % 12
                if kind == 0:
                    value = client.get_sale_catalog(True, True)
                    if len(value['products']) != 200:
                        raise AssertionError('catalog missing test records')
                elif kind == 3:
                    client.cursor.execute('SELECT COUNT(*) FROM products')
                    if client.cursor.fetchone() != (200,):
                        raise AssertionError('product count differed')
                else:
                    rows = client.get_items('Products', limit=30,
                                            search_text='Isolated', search_columns=['name'])
                    if len(rows) != 30:
                        raise AssertionError('paginated product read differed')
            except Exception as exc:
                name = type(exc).__name__
                errors[name] = errors.get(name, 0) + 1
            times.append((time.perf_counter() - start) * 1000)
        return times, errors

    log_dir = tempfile.TemporaryDirectory(prefix='pyli-real-pg-host-logs-')
    handler = RotatingFileHandler(os.path.join(log_dir.name, 'app.log'),
                                  maxBytes=5 * 1024 * 1024, backupCount=3, encoding='utf-8')
    handler.setFormatter(logging.Formatter('%(asctime)s %(levelname)s %(threadName)s %(message)s'))
    server_logger = logging.getLogger('core.network.server')
    server_logger.addHandler(handler)
    monitor_thread = threading.Thread(target=monitor, daemon=True, name='RealPGSoakMonitor')
    monitor_thread.start()
    try:
        with concurrent.futures.ThreadPoolExecutor(max_workers=6) as executor:
            while time.monotonic() - started < seconds:
                if bursts and bursts % 100 == 0:
                    # Existing behavior: each fresh login creates a new token.
                    for client in clients:
                        client.close()
                        client._password = password
                        client.connect()
                    auth_count += len(clients)
                results = list(executor.map(lambda c: one_client(c, bursts), clients))
                bursts += 1
                attempts += 8 * len(clients)
                for timings, errors in results:
                    rpc_latencies.extend(timings)
                    for name, count in errors.items():
                        failed[name] = failed.get(name, 0) + count
                time.sleep(.08)
                if server._checked_out == 0 and not server._httpd.active_requests:
                    recovered += 1
                time.sleep(.22)
    finally:
        stop_monitor.set()
        monitor_thread.join(6)
        server_logger.removeHandler(handler)
        handler.close()
        log_dir.cleanup()
    elapsed = time.monotonic() - started
    final_states = pg_states(monitor_conn)
    result = {
        'real_pg_functional': 'passed',
        'requested_soak_seconds': seconds, 'actual_soak_seconds': round(elapsed, 2),
        'rpc_attempts': attempts, 'failed_rpc_or_probes': sum(failed.values()),
        'failure_categories': failed, 'bursts': bursts, 'recovered_bursts': recovered,
        'logins_during_soak': auth_count, 'sessions_retained': len(server.sessions._sessions),
        'rpc_latency_ms': summarize(rpc_latencies), 'health_latency_ms': summarize(health_latencies),
        'cpu_seconds': round(time.process_time() - cpu_start, 2),
        'cpu_one_core_percent': round((time.process_time() - cpu_start) / elapsed * 100, 2),
        'ram_mb': {'first': samples[0]['ram_mb'] if samples else None,
                   'peak': max((s['ram_mb'] for s in samples if s['ram_mb'] is not None), default=None),
                   'last': samples[-1]['ram_mb'] if samples else None},
        'threads': {'first': samples[0]['threads'] if samples else None,
                    'peak': max((s['threads'] for s in samples), default=None),
                    'last': samples[-1]['threads'] if samples else None},
        'tcp_sockets': {'first': samples[0]['tcp_sockets'] if samples else None,
                        'peak': max((s['tcp_sockets'] for s in samples if s['tcp_sockets'] is not None), default=None),
                        'last': samples[-1]['tcp_sockets'] if samples else None},
        'pool_peak_checked_out': max((s['pool_in_use'] for s in samples), default=0),
        'pool_after_bursts': server._checked_out,
        'http_peak_active': max((s['http_active'] for s in samples), default=0),
        'pg_peak_active': max((s['pg_states'].get('active', 0) for s in samples), default=0),
        'pg_peak_idle': max((s['pg_states'].get('idle', 0) for s in samples), default=0),
        'pg_after_bursts': final_states,
        'health_checks': len(health_latencies), 'host_thread_alive': server.is_running,
    }
    print(json.dumps(result, indent=2), flush=True)
    if failed or recovered != bursts or server._checked_out or elapsed < seconds:
        raise AssertionError('Real PostgreSQL Host soak did not meet its verification criteria')
    return result


def main(seconds=0):
    if not SCRATCH_PARENT.is_dir() or not str(SCRATCH_PARENT.resolve()).lower().endswith(r'\temp\opencode'):
        raise RuntimeError('Preapproved isolated scratch parent is unavailable')
    with tempfile.TemporaryDirectory(prefix='pyli-phase15-', dir=SCRATCH_PARENT) as temporary:
        scratch = Path(temporary)
        data = scratch / 'data'
        port = None
        ctl = PG_BIN / 'pg_ctl.exe'
        env = None
        try:
            data, port, env, ctl = isolated_cluster(scratch)
            control = connect(port)
            try:
                assert_own_cluster(control, data, port)
                print(json.dumps({'isolation_verified': True, 'port': port,
                                  'data_directory': str(data), 'bind': '127.0.0.1'}), flush=True)
                if seconds:
                    control.autocommit = True
                    with control.cursor() as cursor:
                        cursor.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(DB_NAME)))
                    seeded = connect(port, DB_NAME)
                    try:
                        password = seed_isolated_database(seeded)
                    finally:
                        seeded.close()
                    run_workload(port, password, seconds)
            finally:
                control.close()
        finally:
            if (data / 'postmaster.pid').exists():
                stopped = subprocess.run([str(ctl), 'stop', '-D', str(data), '-m', 'fast',
                                          '-w', '-t', '30'], stdout=subprocess.DEVNULL,
                                         stderr=subprocess.DEVNULL, env=env, timeout=40)
                print(json.dumps({'isolated_cluster_stop_exit': stopped.returncode,
                                  'port': port}), flush=True)
                if stopped.returncode:
                    raise RuntimeError('Isolated PostgreSQL did not stop cleanly; preserve scratch directory')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--probe', action='store_true', help='Only initialize and verify an isolated cluster')
    parser.add_argument('--seconds', type=int, default=1800)
    args = parser.parse_args()
    main(0 if args.probe else args.seconds)
