def isolated_cluster(scratch):
    data = scratch / 'data'
    with socket.socket() as reserve:
        reserve.bind(('127.0.0.1', 0))
        port = reserve.getsockname()[1]
    env = os.environ.copy()
    for name in ('PGHOST', 'PGPORT', 'PGDATABASE', 'PGUSER', 'PGPASSWORD', 'PGSERVICE', 'PGDATA'):
        env.pop(name, None)
    initdb = PG_BIN / 'initdb.exe'
    ctl = PG_BIN / 'pg_ctl.exe'
    for binary in (initdb, ctl):
        if not binary.is_file():
            raise RuntimeError(f'Isolated PostgreSQL binary unavailable: {binary.name}')
    initialized = subprocess.run(
        [str(initdb), '-D', str(data), '-U', DB_USER,
         '--auth-host=trust', '--auth-local=trust', '--encoding=UTF8', '--no-instructions'],
        capture_output=True, text=True, errors='replace', env=env, timeout=90,
    )
    if initialized.returncode:
        raise RuntimeError('Temporary cluster initialization failed: ' + initialized.stderr[-1200:])
    log_file = scratch / 'postgres.log'
    started = subprocess.run(
        [str(ctl), 'start', '-D', str(data), '-o', f'-h 127.0.0.1 -p {port}',
         '-l', str(log_file), '-w', '-t', '30'],
        # On Windows the long-lived postgres child can inherit capture pipes;
        # communicate() would then wait forever even after pg_ctl exits.
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, env=env, timeout=45,
    )
    if started.returncode:
        raise RuntimeError(f'Temporary cluster startup failed (exit={started.returncode})')
    return data, port, env, ctl


def connect(port, database='postgres', application='PyLocalInventory-Phase15-Control'):
    return psycopg2.connect(host='127.0.0.1', port=port, dbname=database, user=DB_USER,
                            connect_timeout=5, application_name=application)


def assert_own_cluster(conn, data, port):
    with conn.cursor() as cursor:
        cursor.execute('SHOW data_directory')
        actual = Path(cursor.fetchone()[0]).resolve()
        cursor.execute('SHOW port')
        actual_port = int(cursor.fetchone()[0])
        cursor.execute('SHOW listen_addresses')
        address = cursor.fetchone()[0]
    conn.rollback()
    if actual != data.resolve() or actual_port != port or address != '127.0.0.1':
        raise RuntimeError('Refusing to use PostgreSQL: isolated cluster identity did not match')


